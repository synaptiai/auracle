/**
 * Deterministic offline stand-in model for replay runs (section 4.10).
 *
 * Replay must never touch the network: DEC-18 keeps real traffic out of the
 * repository and DEC-20 wants a reproducible history pass. This provider
 * answers classifier prompts by matching fixture topic phrases in the ticket
 * text, so a replay run is byte-for-byte reproducible without a recorded
 * transcript. The phrase table mirrors the synthetic corpus only; it is test
 * tooling, not the production model port (DEC-16 keeps that with OpenRouter).
 */

import type {
  ChatRequest,
  ChatResult,
  EmbeddingRequest,
  EmbeddingResult,
  ModelProvider,
  PinnedVersions,
} from '../models/provider.js';

/**
 * Phrase table: first match wins, so more specific phrases come first.
 * Every phrase appears verbatim in fixtures generated by
 * scripts/generate-fixtures.mjs. 'other' is the fallback group (section 4.11).
 */
const PHRASES: readonly { intentId: string; phrase: string }[] = [
  { intentId: 'chargeback-notice', phrase: 'bank started a dispute' },
  { intentId: 'billing-dispute', phrase: 'invoice total' },
  { intentId: 'refund-request', phrase: 'refund' },
  { intentId: 'cancel-subscription', phrase: 'subscription' },
  { intentId: 'data-deletion-request', phrase: 'deletion policy' },
  { intentId: 'payment-failure', phrase: 'decline' },
  { intentId: 'plan-change-question', phrase: 'annual billing' },
  { intentId: 'invoice-copy-request', phrase: 'copy of the invoice' },
  { intentId: 'account-recovery', phrase: 'backup codes' },
  { intentId: 'login-trouble', phrase: 'reset message' },
  { intentId: 'sync-error-report', phrase: 'sync' },
  { intentId: 'export-broken', phrase: 'export' },
  { intentId: 'integration-failure', phrase: 'calendar connection' },
  { intentId: 'feature-request', phrase: 'saved filter views' },
  { intentId: 'how-to-question', phrase: 'assignee' },
  { intentId: 'pricing-question', phrase: 'plan limit' },
  { intentId: 'documentation-gap', phrase: 'import guide' },
  { intentId: 'feedback-positive', phrase: 'weekly summary' },
  { intentId: 'bug-minor-report', phrase: 'typo' },
  { intentId: 'onboarding-help', phrase: 'setup checklist' },
  { intentId: 'notification-settings-help', phrase: 'digest' },
  { intentId: 'mobile-app-question', phrase: 'offline' },
  { intentId: 'api-usage-question', phrase: 'cursor' },
  { intentId: 'status-inquiry', phrase: 'incident' },
];

const FALLBACK_INTENT = 'other';

export function predictIntent(text: string): string {
  const lowered = text.toLowerCase();
  for (const entry of PHRASES) {
    if (lowered.includes(entry.phrase)) return entry.intentId;
  }
  return FALLBACK_INTENT;
}

/** Stand-in provider: same answer on every sample, no network, no state. */
export class ReplayStubProvider implements ModelProvider {
  /** This is the offline stand-in; no published number may claim otherwise. */
  readonly kind = 'stub' as const;
  readonly chatCalls: ChatRequest[] = [];

  async complete(
    call: ChatRequest & PinnedVersions & { dataGuarantee?: { zdrOnly?: boolean } },
  ): Promise<ChatResult> {
    const userMessage = call.messages.at(-1);
    const record: ChatRequest = {
      messages: call.messages,
      temperature: call.temperature,
    };
    if (call.maxOutputTokens !== undefined) {
      record.maxOutputTokens = call.maxOutputTokens;
    }
    this.chatCalls.push(record);
    return {
      text: predictIntent(userMessage?.content ?? ''),
      costMicros: 0,
      usage: { promptTokens: 0, completionTokens: 0, totalTokens: 0 },
      servedModelVer: call.modelVer,
    };
  }

  async embed(
    _call: EmbeddingRequest & PinnedVersions & { dataGuarantee?: { zdrOnly?: boolean } },
  ): Promise<EmbeddingResult> {
    throw new Error('replay stub does not embed; action match needs no retrieval');
  }
}
